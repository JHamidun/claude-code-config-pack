# ---------------------------------------------------------------------------
def read(rel):
    with open(os.path.join(ROOT, rel), encoding="utf-8") as fh:
        return fh.read()


def write(rel, text):
    with open(os.path.join(ROOT, rel), "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)


def insert_after_frontmatter(text, block):
    """Put block right after the YAML frontmatter (or at the very top)."""
    lines = text.split("\n")
    idx = 0
    if lines and lines[0].strip() == "---":
        for i in range(1, len(lines)):
            if lines[i].strip() == "---":
                idx = i + 1
                break
    head = lines[:idx]
    tail = lines[idx:]
    while tail and tail[0].strip() == "":
        tail.pop(0)
    return "\n".join(head + ["", block, ""] + tail)


def check_template():
    """Every secret-looking var must stay commented out.

    A placeholder like `OPENAI_API_KEY=your_openai_api_key` is a NON-EMPTY string,
    so `if not os.getenv(...)` guards read it as configured and the tool sends the
    placeholder upstream — the user gets a bare 401 instead of "key is not set".
    """
    bad = []
    for n, line in enumerate(read(TEMPLATE).split("\n"), 1):
        m = re.match(r"^([A-Za-z0-9_]+)\s*=", line)
        if m and SECRETISH.search(m.group(1)):
            bad.append((n, m.group(1)))
    return bad


def check(verbose=True):
    problems = []

    missing_guard = [f for f in GUARD_FILES
                     if not os.path.isfile(os.path.join(ROOT, f)) or MARKER not in read(f)]
    for f in missing_guard:
        problems.append("NO-KEY GUARD missing: " + f)

    for rel, probe, _anchor, _text in POLICY:
        if not os.path.isfile(os.path.join(ROOT, rel)):
            problems.append("policy file missing: " + rel)
        elif not re.search(probe, read(rel)):
            problems.append("free-by-default policy text missing in %s (probe: %s)" % (rel, probe))

    for n, var in check_template():
        problems.append("%s:%d — %s ships UNCOMMENTED (placeholder defeats "
                        "`if not key` guards)" % (TEMPLATE, n, var))

    if verbose:
        print("=== FREE-BY-DEFAULT GUARD ===")
        print("guard blocks: %d/%d files" % (len(GUARD_FILES) - len(missing_guard), len(GUARD_FILES)))
        if problems:
            print("FAIL — %d problem(s):" % len(problems))
            for p in problems:
                print("  x " + p)
            print("\nFix: python guard_free_by_default.py --apply   (then re-run _build_plugins.py)")
        else:
            print("OK — pack works with zero third-party API keys.")
    return problems


def apply(dry=False):
    changes = []

    for rel in GUARD_FILES:
        path = os.path.join(ROOT, rel)
        if not os.path.isfile(path):
            changes.append(("SKIP (absent)", rel, ""))
            continue
        text = read(rel)
        if MARKER in text:
            continue
        new = insert_after_frontmatter(text, GUARD_BLOCK)
        changes.append(("insert guard block", rel, "after frontmatter"))
        if not dry:
            write(rel, new)

    for rel, probe, anchor, ins in POLICY:
        path = os.path.join(ROOT, rel)
        if not os.path.isfile(path):
            changes.append(("SKIP (absent)", rel, ""))
            continue
        text = read(rel)
        if re.search(probe, text):
            continue

        if rel == ".claude/config/models.md":
            m = re.search(anchor, text, re.M)
            if not m:
                changes.append(("MANUAL — anchor not found", rel, anchor))
                continue
            new = text[:m.start()] + MODELS_BLOCK + "\n" + text[m.start():]
            changes.append(("insert NO-KEY policy block", rel, "before '## Контекст использования'"))
        elif rel in INSTALLER_FIXES:
            new = text
            done = []
            for old, repl in INSTALLER_FIXES[rel]:
                if old in new:
                    new = new.replace(old, repl, 1)
                    done.append(old[:44])
            if not done:
                changes.append(("MANUAL — installer text drifted", rel, ""))
                continue
            changes.append(("rewrite installer message", rel, "; ".join(done)))
        elif rel == ".claude/config/rules-ref/onboarding.md":
            new = text
            done = []
            for old, repl in ONBOARDING_FIXES:
                if old in new:
                    new = new.replace(old, repl)
                    done.append(old.split("\n")[0][:50])
            if not done:
                changes.append(("MANUAL — onboarding text drifted", rel, ""))
                continue
            changes.append(("rewrite onboarding steps", rel, "; ".join(done)))
        else:
            m = re.search(anchor, text, re.M)
            if not m:
                changes.append(("MANUAL — anchor not found", rel, anchor))
                continue
            head, tail = text[:m.end()], text[m.end():]
            if rel == ".claude/rules/dont-do.md":
                # the new rule takes slot 11; the existing item 11 becomes 12
                tail = re.sub(r"^11\. ", "12. ", tail, count=1, flags=re.M)
                ins = ins + "\n12. НЕ используй НЕ ТУ модель для генерации изображений " \
                            "(сама генерация — ОПЦИОНАЛЬНАЯ фича, только при настроенном " \
                            "GOOGLE_API_KEY; без ключа — см. п.11) — ТОЛЬКО:"
                tail = re.sub(r"^12\. НЕ используй НЕ ТУ модель[^\n]*\n", "", tail,
                              count=1, flags=re.M)
            new = head + "\n" + ins + tail
            changes.append(("insert policy line", rel, "after " + anchor))

        if not dry:
            write(rel, new)

    bad_template = check_template()
    if bad_template:
        lines = read(TEMPLATE).split("\n")
        for n, var in bad_template:
            raw = lines[n - 1]
            value = raw.split("=", 1)[1].strip()
            # keep an obvious placeholder as a hint; never keep something that
            # looks like a real pasted secret sitting in a public template
            hint = value if PLACEHOLDERISH.match(value) else "value removed by guard"
            lines[n - 1] = "# %s=          # %s" % (var, hint) if hint else "# %s=" % var
            changes.append(("comment out (was live)", TEMPLATE, "line %d: %s" % (n, var)))
        if not dry:
            write(TEMPLATE, "\n".join(lines))

    verb = "WOULD CHANGE" if dry else "CHANGED"
    print("=== %s (%d) ===" % (verb, len(changes)))
    for what, rel, detail in changes:
        print("  %-32s %s %s" % (what, rel, ("(%s)" % detail) if detail else ""))
    if not changes:
        print("  nothing to do — guard already intact")
    if not dry and any(r.startswith(".claude/") for _, r, _ in changes):
        print("\nNOTE: .claude/ changed — re-run `python _build_plugins.py` "
              "so plugins/ mirrors pick it up.")
    return changes


if __name__ == "__main__":
    arg = sys.argv[1] if len(sys.argv) > 1 else "--check"
    if arg == "--apply":
        apply(dry=False)
        sys.exit(1 if check() else 0)
    elif arg == "--dry-run":
        apply(dry=True)
        sys.exit(0)
    else:
        sys.exit(1 if check() else 0)
