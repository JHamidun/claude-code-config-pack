"""free-by-default guard (TRACKED FILE — must not be gitignored) — keeps the pack working with ZERO third-party API keys.

WHY THIS FILE EXISTS
--------------------
The pack's `.claude/` tree is periodically re-synced wholesale from a live
personal config. A wholesale sync overwrites files, so any hand-made policy
edit inside them is silently lost. That is exactly how the "free-by-default"
fix (commit 46036a6, 2026-07-21) died twice:

    46036a6  2026-07-21  16 files carry the NO-KEY GUARD
    3ad0da6  2026-07-24  10 files   <- first sync ate 6
    3a337b6  2026-07-31   0 files   <- second sync ate the rest
    01dd6cb  2026-08-03   0 files   <- shipped to origin/main

So the guard must NOT live only inside synced files. It lives HERE, and is
re-applied on top of the sync:

    sync .claude/  ->  python guard_free_by_default.py --apply  ->  python _build_plugins.py

`--check` is the gate: it fails loudly (exit 1) when anything went missing.
`_check.py` calls it, and CI runs it on every push/PR.

USAGE
-----
    python guard_free_by_default.py            # same as --check
    python guard_free_by_default.py --check    # verify; exit 1 if the guard eroded
    python guard_free_by_default.py --dry-run  # show exactly what --apply would change
    python guard_free_by_default.py --apply    # restore everything (idempotent)
"""
