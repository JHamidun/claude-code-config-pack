#!/bin/bash
# grep_suspicious_facts.sh — поиск фабрикованных «личных» цифр и сцен после subagent-passes.
#
# Запускать после краfт-pass (v12, v13, ...) до финального build.
# Субагенты массово выдумывают конкретные числа компании автора
# («320 часов на развёртывание», «18 миллионов рублей», «5 экспериментов, 2 свернул»)
# и синтетические сенсорные сцены («ладони пахли», «свистит чайник») — звучит
# правдоподобно именно потому, что проверить это снаружи невозможно.
#
# Скрипт находит все подозрительные совпадения и группирует по типу.
#
# Две группы настраиваются под свою книгу через переменные окружения:
#   BOOK_REPEAT_PHRASES — авторские обороты, которые склонны повторяться из главы
#                         в главу (в тексте их не видно, в книге подряд — режет глаз)
#   BOOK_BANNED_NAMES   — имена персонажей из отменённых версий книги, которые
#                         субагент может втащить обратно
# Обе — регулярка в синтаксисе grep -E, альтернативы через «|». Пусто — группа пропускается.

set -e

if [ -z "${BOOK_ROOT:-}" ]; then
  echo "BOOK_ROOT не задан. Это путь к корню книги (папка с chapters/). Пример: export BOOK_ROOT=./book" >&2
  exit 1
fi
VERSION="${1:-v13}"

REPEAT_PHRASES="${BOOK_REPEAT_PHRASES:-}"
BANNED_NAMES="${BOOK_BANNED_NAMES:-}"

CHAPTERS_DIR="$BOOK_ROOT/chapters"

echo ""
echo "=== Suspicious facts scan for $VERSION ==="
echo "BOOK_ROOT: $BOOK_ROOT"
echo ""

cd "$CHAPTERS_DIR"

# Group 1 — фабрикованные «внутренние» цифры компании автора (часы, рубли, эксперименты)
echo "=== Group 1. Подозрительные «личные» числа ==="
echo "Маркеры: точные часы on-prem, миллионы рублей, конкретное число экспериментов"
echo "  → Проверить против ANCHORS.md / SOURCES.md / personal stories. Если нет — смягчить до качественного описания."
echo ""

grep -rnE 'около [0-9]+ (миллион|часов|месяц|недел)' */DRAFT.${VERSION}.md 2>/dev/null || echo "  [нет совпадений]"
echo "---"
grep -rnE '[0-9]+ часов на (первичное|развёрт|внедрен|сопровождение)' */DRAFT.${VERSION}.md 2>/dev/null || echo "  [нет совпадений]"
echo "---"
grep -rnE 'из [0-9]+ (моих|наших) экспериментов' */DRAFT.${VERSION}.md 2>/dev/null || echo "  [нет совпадений]"
echo "---"
grep -rnE '[0-9]+ миллион(ов|а)? рублей' */DRAFT.${VERSION}.md 2>/dev/null || echo "  [нет совпадений]"
echo "---"
grep -rnE 'занял около [0-9]+' */DRAFT.${VERSION}.md 2>/dev/null || echo "  [нет совпадений]"
echo ""

# Group 2 — синтетические сенсорные детали
echo "=== Group 2. Синтетические сенсорные детали ==="
echo "Маркеры: запах, звук, тактильность в синтетических сценах"
echo "  → Проверить, описана ли сцена в ANCHORS.md. Если нет — убрать сенсорику."
echo ""

grep -rnE 'ладони пах(ли|нул)' */DRAFT.${VERSION}.md 2>/dev/null || echo "  [нет совпадений]"
echo "---"
grep -rnE 'свистит чайник|гудел кондиционер|пахло (кофе|дождём)' */DRAFT.${VERSION}.md 2>/dev/null || echo "  [нет совпадений]"
echo "---"
grep -rnE '(моросил|накрапывал) дождь' */DRAFT.${VERSION}.md 2>/dev/null || echo "  [нет совпадений]"
echo ""

# Group 3 — манипулятивная срочность в финалах
echo "=== Group 3. Манипулятивная срочность (Pattern 21) ==="
grep -rnE 'потом будет поздно|второго шанса не будет|последний шанс|пока не поздно' */DRAFT.${VERSION}.md 2>/dev/null || echo "  [нет совпадений]"
echo ""

# Group 4 — самопохвала читателю
echo "=== Group 4. Самопохвала читателю (Pattern 22) ==="
grep -rnE 'ты (теперь )?знаешь больше [0-9]+%|опережаешь большинство|понимаешь то, что (другие|остальные)' */DRAFT.${VERSION}.md 2>/dev/null || echo "  [нет совпадений]"
echo ""

# Group 5 — гладкие проценты без базы
echo "=== Group 5. Гладкие проценты без базы (Pattern 17) ==="
echo "  → Проверить, есть ли источник у каждого. Если 70%/30% автора — нужна база."
echo ""
grep -rnE 'примерно (70|30|50)%' */DRAFT.${VERSION}.md 2>/dev/null | head -20 || echo "  [нет совпадений]"
echo ""

# Group 6 — повторяющиеся авторские обороты (настраивается: BOOK_REPEAT_PHRASES)
echo "=== Group 6. Повторяющиеся авторские обороты ==="
if [ -n "$REPEAT_PHRASES" ]; then
  echo "  → Оборот, встреченный больше одного раза на книгу, читается как тик автора."
  echo ""
  grep -rncE "$REPEAT_PHRASES" */DRAFT.${VERSION}.md 2>/dev/null | grep -v ':0$' || echo "  [нет совпадений >0]"
else
  echo "  [пропущено: BOOK_REPEAT_PHRASES не задан]"
  echo "  Пример: export BOOK_REPEAT_PHRASES='об этом редко говорят|как ни странно'"
fi
echo ""

# Group 7 — выдуманные исследования
echo "=== Group 7. Подозрительные источники ==="
echo "  → Проверить через WebSearch / Perplexity"
echo ""
grep -rnE 'MIT 202[4567]|Stanford 202[4567]|Harvard 202[4567]' */DRAFT.${VERSION}.md 2>/dev/null || echo "  [нет совпадений]"
echo ""

# Group 8 — забытые персонажи старой попытки (настраивается: BOOK_BANNED_NAMES)
echo "=== Group 8. Персонажи из отменённых версий книги (ЗАПРЕТ) ==="
if [ -n "$BANNED_NAMES" ]; then
  echo "  → Субагент, читавший старый черновик, тащит их обратно как «сквозных героев»."
  echo ""
  grep -rnE "$BANNED_NAMES" */DRAFT.${VERSION}.md 2>/dev/null || echo "  [нет совпадений]"
else
  echo "  [пропущено: BOOK_BANNED_NAMES не задан]"
  echo "  Пример: export BOOK_BANNED_NAMES='Имя Фамилия|Маша из регионального филиала'"
fi
echo ""

echo "=== Done ==="
echo ""
echo "Для каждого найденного маркера:"
echo "  1. Открыть указанную строку"
echo "  2. Проверить против ANCHORS.md / SOURCES.md этой главы"
echo "  3. Если фабрикация — смягчить или удалить"
echo "  4. Если реальный факт — добавить в SOURCES.md с атрибуцией"
